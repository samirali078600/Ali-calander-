export function getHolidaysForDate(dateStr: string, stateCode: string = 'ALL'): HolidayItem[] {
  return HOLIDAYS_DATABASE.filter(h => {
    const isSameDate = h.date === dateStr;
    const isMatchingState = stateCode === 'ALL' || h.stateCode === 'ALL' || h.stateCode === stateCode;
    return isSameDate && isMatchingState;
  });
}
